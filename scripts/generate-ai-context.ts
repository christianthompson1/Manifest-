/**
 * Manifest Studio - Lightweight AI Context Generator
 * Scans repository sources, Rust MVM crates, packages, tests, and examples to generate
 * an accurate, grounded, non-normative repository summary.
 *
 * Run with: npx tsx scripts/generate-ai-context.ts
 */

import * as fs from 'fs';
import * as path from 'path';

function scanDir(dir: string, exts: string[]): string[] {
  let results: string[] = [];
  if (!fs.existsSync(dir)) return results;
  for (const file of fs.readdirSync(dir)) {
    if (file === 'target' || file === 'node_modules' || file === '.git') continue;
    const fullPath = path.join(dir, file);
    const stat = fs.statSync(fullPath);
    if (stat.isDirectory()) {
      results = results.concat(scanDir(fullPath, exts));
    } else if (exts.some((e) => fullPath.endsWith(e))) {
      results.push(fullPath);
    }
  }
  return results;
}

export function generateContext(): string {
  const pkg = JSON.parse(fs.readFileSync('package.json', 'utf-8'));
  const manifestCoreFiles = scanDir('manifest-core/src', ['.ts']);
  const mvmRustFiles = scanDir('mvm/crates', ['.rs']);
  const studioFiles = scanDir('src/studio', ['.ts', '.tsx']);
  const testFiles = scanDir('manifest-core/tests', ['.ts']);
  const exampleFiles = scanDir('examples', ['.manifest']);

  const lines: string[] = [];
  lines.push('# Manifest Studio — Auto-Generated Repository Summary (Non-Normative)');
  lines.push('');
  lines.push(
    '> **Non-Normative Generated Summary:** This file is automatically generated by `scripts/generate-ai-context.ts`. It is **not** a normative language or VM specification. For authoritative specifications, consult [`LANGUAGE_SPEC.md`](./LANGUAGE_SPEC.md), [`BYTECODE_SPEC.md`](./BYTECODE_SPEC.md), [`VM_SPEC.md`](./VM_SPEC.md), [`COMPILER_TARGETS.md`](./COMPILER_TARGETS.md), [`STANDARD_LIBRARY.md`](./STANDARD_LIBRARY.md), [`SECURITY_MODEL.md`](./SECURITY_MODEL.md), and [`ARCHITECTURE.md`](./ARCHITECTURE.md).'
  );
  lines.push('');
  lines.push(`Generated at: ${new Date().toISOString()}`);
  lines.push('');
  lines.push('## Package & Workspace Inventory');
  lines.push(`- Application Package: \`${pkg.name}\` (\`manifest-core\` v1.0.0 + \`mvm\` v1.0.0)`);
  lines.push(`- Runtime Dependencies: ${Object.keys(pkg.dependencies || {}).length} npm packages`);
  lines.push(`- Dev Dependencies: ${Object.keys(pkg.devDependencies || {}).length} npm packages`);
  lines.push(`- Manifest Core Compiler/Frontend (\`manifest-core/src/\`): ${manifestCoreFiles.length} TypeScript modules`);
  lines.push(`- Rust Manifest Virtual Machine (\`mvm/crates/\`): ${mvmRustFiles.length} Rust source files (\`#![forbid(unsafe_code)]\` in \`mvm-core\`)`);
  lines.push(`- Manifest Studio IDE (\`src/studio/\`): ${studioFiles.length} React 19 / CodeMirror 6 modules`);
  lines.push(`- Automated Test Runners (\`manifest-core/tests/\`): ${testFiles.length} test suites`);
  lines.push(`- Verified Example Programs (\`examples/\`): ${exampleFiles.length} \`.manifest\` programs`);
  lines.push('');
  lines.push('## Authoritative Documentation Map');
  lines.push('- [`LANGUAGE.md`](./LANGUAGE.md) — Accessible overview & Beginner vs Professional syntax guide');
  lines.push('- [`LANGUAGE_SPEC.md`](./LANGUAGE_SPEC.md) — Formal Manifest v1.0 language specification (26 sections + EBNF)');
  lines.push('- [`BYTECODE_SPEC.md`](./BYTECODE_SPEC.md) — Binary `.mbc` v1.0 container format, opcodes & static verifier');
  lines.push('- [`VM_SPEC.md`](./VM_SPEC.md) — Rust Manifest Virtual Machine (`mvm-core`, `mvm-cli`, `mvm-wasm`) specification');
  lines.push('- [`COMPILER_TARGETS.md`](./COMPILER_TARGETS.md) — Target matrix (`mvm`, `web-js`, `wasm`, `native`, `solana-sbf`, and planned targets)');
  lines.push('- [`STANDARD_LIBRARY.md`](./STANDARD_LIBRARY.md) — `std::*` namespaces & capability requirements');
  lines.push('- [`SECURITY_MODEL.md`](./SECURITY_MODEL.md) — Compile-time capability/effect verification & runtime enforcement');
  lines.push('- [`ARCHITECTURE.md`](./ARCHITECTURE.md) — End-to-end compiler, VM, and Manifest Studio IDE architecture');
  lines.push('- [`LANGUAGE_SUPPORT.md`](./LANGUAGE_SUPPORT.md) — Honest IDE language & execution capability matrix');
  lines.push('- [`IMPLEMENTATION_ROADMAP.md`](./IMPLEMENTATION_ROADMAP.md) — Verified status vs remaining roadmap');
  lines.push('- [`verification/VERIFICATION_BASELINE.md`](./verification/VERIFICATION_BASELINE.md) — Recorded test & verification results');
  lines.push('- [`verification/PERFORMANCE.md`](./verification/PERFORMANCE.md) — Compiler, TS evaluator, WASM, and Rust MVM benchmarks');
  lines.push('');
  lines.push('## Verification Commands');
  lines.push('- Rust MVM unit & verifier tests: `cargo test --manifest-path mvm/Cargo.toml`');
  lines.push('- TypeScript typecheck: `npm run lint`');
  lines.push('- Full Manifest v0.1–v1.0 + Studio + MVM test suite: `npm run manifest:test`');
  lines.push('- Compiler & Rust MVM benchmarks: `npm run manifest:bench`');
  lines.push('- Production bundle: `npm run build`');

  return lines.join('\n') + '\n';
}

if (
  typeof process !== 'undefined' &&
  process.argv &&
  process.argv[1] &&
  process.argv[1].endsWith('generate-ai-context.ts')
) {
  const summary = generateContext();
  const outPath = path.join('docs', 'AI_CONTEXT_SUMMARY.md');
  fs.writeFileSync(outPath, summary, 'utf-8');
  console.log(`✓ AI context summary refreshed and written to ${outPath}`);
}
