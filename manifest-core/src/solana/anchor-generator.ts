/**
 * Manifest Solana Target Compiler - Anchor Rust Generator
 * Transforms Solana IR into production-ready Anchor 0.30+ compatible Rust code
 * and corresponding Anchor IDL JSON definition.
 */

import { SolanaProgramIR, SolanaAccountIR, SolanaInstructionIR } from './solana-ir.ts';
import { SourceMapGenerator } from '../sourcemap/sourcemap.ts';

export interface AnchorCompilationResult {
  rustCode: string;
  idlJson: string;
  idl?: any;
  sourceMap?: SourceMapGenerator;
  programId: string;
}

export class AnchorGenerator {
  public static generate(
    program: SolanaProgramIR,
    sourceMapGenerator?: SourceMapGenerator
  ): AnchorCompilationResult {
    const lines: string[] = [];

    // Header & imports
    lines.push('// Generated by Manifest Solana Compiler v0.4');
    lines.push('// Target: Solana Anchor Framework (v0.30+)');
    lines.push('use anchor_lang::prelude::*;');
    lines.push('use anchor_spl::token::{self, Token, TokenAccount, Transfer};');
    lines.push('');
    lines.push(`declare_id!("${program.programId}");`);
    lines.push('');

    // Program module
    lines.push('#[program]');
    lines.push(`pub mod ${this.toSnakeCase(program.programName)} {`);
    lines.push('    use super::*;');
    lines.push('');

    for (const inst of program.instructions) {
      const instSnake = this.toSnakeCase(inst.name);
      const ctxStructName = `${this.toPascalCase(inst.name)}Context`;
      lines.push(`    pub fn ${instSnake}(ctx: Context<${ctxStructName}>) -> Result<()> {`);

      // Account references
      for (const acc of inst.accounts) {
        if (acc.accountType) {
          lines.push(`        let ${this.toSnakeCase(acc.name)} = &mut ctx.accounts.${this.toSnakeCase(acc.name)};`);
        }
      }

      // Constraints / requires
      for (const req of inst.requires) {
        const rustCondition = this.translateConditionToRust(req);
        lines.push(`        require!(${rustCondition}, ErrorCode::ConstraintFailed);`);
      }

      // State mutations
      for (const mutItem of inst.mutations) {
        lines.push(`        ${mutItem.target} = ${mutItem.expression};`);
      }

      // CPI calls
      for (const cpi of inst.cpis) {
        if (cpi.targetProgram.toLowerCase() === 'token') {
          lines.push('        // CPI: SPL Token Transfer');
          lines.push('        let cpi_accounts = Transfer {');
          lines.push('            from: ctx.accounts.source.to_account_info(),');
          lines.push('            to: ctx.accounts.destination.to_account_info(),');
          lines.push('            authority: ctx.accounts.authority.to_account_info(),');
          lines.push('        };');
          lines.push('        let cpi_program = ctx.accounts.token_program.to_account_info();');
          lines.push('        let cpi_ctx = CpiContext::new(cpi_program, cpi_accounts);');
          lines.push(`        token::transfer(cpi_ctx, ${cpi.params.amount || '0'})?;`);
        } else {
          lines.push(`        // Custom CPI to ${cpi.targetProgram}::${cpi.instructionName}`);
        }
      }

      // Raw Rust escape hatch inside instruction
      if (inst.rawRust) {
        lines.push('        // --- Manifest Raw Rust Escape Hatch ---');
        lines.push(`        ${inst.rawRust.trim()}`);
        lines.push('        // -------------------------------------');
      }

      lines.push('        Ok(())');
      lines.push('    }');
      lines.push('');
    }

    lines.push('}');
    lines.push('');

    // Instruction Context Structs (#[derive(Accounts)])
    for (const inst of program.instructions) {
      const ctxStructName = `${this.toPascalCase(inst.name)}Context<'info>`;
      lines.push('#[derive(Accounts)]');
      lines.push(`pub struct ${ctxStructName} {`);

      for (const acc of inst.accounts) {
        const accSnake = this.toSnakeCase(acc.name);
        const mutAttr = acc.isMut ? '#[account(mut)]\n    ' : '';
        const signerAttr = acc.isSigner ? '#[account(signer)]\n    ' : '';
        const typeStr = acc.accountType
          ? `Account<'info, ${this.toPascalCase(acc.accountType)}>`
          : acc.isSigner
          ? "Signer<'info>"
          : "AccountInfo<'info>";

        lines.push(`    ${mutAttr}${signerAttr}pub ${accSnake}: ${typeStr},`);
      }

      // If instruction uses CPI token, ensure token_program is added
      if (inst.cpis.some(c => c.targetProgram.toLowerCase() === 'token')) {
        lines.push("    pub token_program: Program<'info, Token>,");
      }

      lines.push("    pub system_program: Program<'info, System>,");
      lines.push('}');
      lines.push('');
    }

    // Account Data Schemas (#[account])
    for (const acc of program.accounts) {
      const typeName = this.toPascalCase(acc.name);
      lines.push('#[account]');
      lines.push('#[derive(Default)]');
      lines.push(`pub struct ${typeName} {`);
      for (const field of acc.fields) {
        const fieldType = this.toRustType(field.fieldType);
        lines.push(`    pub ${this.toSnakeCase(field.name)}: ${fieldType},`);
      }
      lines.push('}');
      lines.push('');
    }

    // Error Codes
    lines.push('#[error_code]');
    lines.push('pub enum ErrorCode {');
    lines.push('    #[msg("Constraint validation failed in Manifest instruction")]');
    lines.push('    ConstraintFailed,');
    lines.push('    #[msg("Unauthorized signer for this instruction")]');
    lines.push('    Unauthorized,');
    lines.push('}');
    lines.push('');

    // Global Raw Rust Escape Hatch if present
    if (program.rawRustEscape) {
      lines.push('// ==========================================');
      lines.push('// Manifest Raw Rust Escape Hatch');
      lines.push('// ==========================================');
      lines.push(program.rawRustEscape.trim());
      lines.push('');
    }

    const rustCode = lines.join('\n');

    // Build IDL JSON
    const idl = this.generateIdl(program);

    return {
      rustCode,
      idlJson: JSON.stringify(idl, null, 2),
      idl,
      sourceMap: sourceMapGenerator,
      programId: program.programId,
    };
  }

  private static generateIdl(program: SolanaProgramIR): any {
    return {
      version: '0.1.0',
      name: this.toSnakeCase(program.programName),
      address: program.programId,
      metadata: {
        name: program.programName,
        version: '0.1.0',
        spec: '0.1.0',
        description: `Generated by Manifest Solana target for ${program.programName}`,
      },
      instructions: program.instructions.map((inst) => ({
        name: this.toSnakeCase(inst.name),
        accounts: inst.accounts.map((a) => ({
          name: this.toSnakeCase(a.name),
          isMut: a.isMut,
          isSigner: a.isSigner,
        })),
        args: [],
      })),
      accounts: program.accounts.map((acc) => ({
        name: this.toPascalCase(acc.name),
        type: {
          kind: 'struct',
          fields: acc.fields.map((f) => ({
            name: this.toSnakeCase(f.name),
            type: this.toIdlType(f.fieldType),
          })),
        },
      })),
      errors: [
        { code: 6000, name: 'ConstraintFailed', msg: 'Constraint validation failed in Manifest instruction' },
        { code: 6001, name: 'Unauthorized', msg: 'Unauthorized signer for this instruction' },
      ],
    };
  }

  private static translateConditionToRust(condition: string): string {
    return condition
      .replace(/\band\b/gi, '&&')
      .replace(/\bor\b/gi, '||')
      .replace(/([^=!<>]|^)=([^=]|$)/g, '$1==$2')
      .replace(/signer/gi, 'ctx.accounts.authority.key()')
      .replace(/authority/gi, 'ctx.accounts.authority.key()');
  }

  private static toRustType(t: string): string {
    switch (t.toLowerCase()) {
      case 'number':
      case 'u64':
        return 'u64';
      case 'u32':
        return 'u32';
      case 'i64':
        return 'i64';
      case 'bool':
      case 'boolean':
        return 'bool';
      case 'text':
      case 'string':
        return 'String';
      case 'address':
      case 'pubkey':
        return 'Pubkey';
      default:
        return 'u64';
    }
  }

  private static toIdlType(t: string): string {
    switch (t.toLowerCase()) {
      case 'number':
      case 'u64':
        return 'u64';
      case 'u32':
        return 'u32';
      case 'i64':
        return 'i64';
      case 'bool':
      case 'boolean':
        return 'bool';
      case 'text':
      case 'string':
        return 'string';
      case 'address':
      case 'pubkey':
        return 'publicKey';
      default:
        return 'u64';
    }
  }

  private static toSnakeCase(str: string): string {
    return str
      .replace(/([A-Z])/g, '_$1')
      .toLowerCase()
      .replace(/^_/, '');
  }

  private static toPascalCase(str: string): string {
    return str.replace(/(^|_)([a-z])/g, (_, __, letter) => letter.toUpperCase());
  }
}
