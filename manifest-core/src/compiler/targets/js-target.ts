  private generateInstructionStatements(handlers: any[], lines: string[]): void {
    for (const h of handlers || []) {
      const instList = h.body || h.instructions || [];
      this.emitInstructions(instList, lines, '    ', false);
    }
  }

  private applyStyles(elementVar: string, styles: Record<string, string | number> | undefined, lines: string[]): void {
    if (!styles) return;
    for (const [rawKey, val] of Object.entries(styles)) {
      const kebab = rawKey.replace(/[A-Z]/g, (m) => `-${m.toLowerCase()}`).replace(/_/g, '-').toLowerCase();
      const camel = kebab.replace(/-([a-z])/g, (_, g) => g.toUpperCase());
      const safeVal = String(val).replace(/\\/g, '\\\\').replace(/"/g, '\\"');
      lines.push(`  if (${elementVar} && ${elementVar}.style) {`);
      lines.push(`    try { ${elementVar}.style.setProperty("${kebab}", "${safeVal}"); } catch (_) {}`);
      lines.push(`    try { ${elementVar}.style["${camel}"] = "${safeVal}"; } catch (_) {}`);
      lines.push(`  }`);
    }
  }

  private exprToReadable(expr: any): string {
    if (expr === null || expr === undefined) return '""';
    if (typeof expr === 'string' || typeof expr === 'number' || typeof expr === 'boolean') {
      return JSON.stringify(expr);
    }
    const kind = expr.kind || expr.type;
    if (kind === 'IRLiteral' || kind === 'Literal') return JSON.stringify(expr.value);
    if (kind === 'IRVariableRef' || kind === 'Identifier') return String(expr.name);
    if (kind === 'IRBinaryOp' || kind === 'BinaryExpression') {
      return `(${this.exprToReadable(expr.left)} ${expr.operator} ${this.exprToReadable(expr.right)})`;
    }
    return '';
  }

  private exprToJs(expr: any, _preferLocal = false, preferEmptyFallback = false): string {
    if (expr === null || expr === undefined) return '""';
    if (typeof expr === 'string' || typeof expr === 'number' || typeof expr === 'boolean') {
      return JSON.stringify(expr);
    }
    const kind = expr.kind || expr.type;
    switch (kind) {
      case 'IRLiteral':
      case 'Literal':
        return JSON.stringify(expr.value);
      case 'IRVariableRef':
      case 'Identifier': {
        return `__manifest.getVar(${JSON.stringify(expr.name)}, __locals, ${preferEmptyFallback})`;
      }
      case 'IRBinaryOp':
      case 'BinaryExpression': {
        const left = this.exprToJs(expr.left, _preferLocal, preferEmptyFallback);
        const right = this.exprToJs(expr.right, _preferLocal, preferEmptyFallback);
        const rawOp = expr.operator;
        if (rawOp === '/') {
          return `__manifest.div(${left}, ${right})`;
        }
        if (rawOp === '%') {
          return `__manifest.mod(${left}, ${right})`;
        }
        let op = rawOp;
        if (op === '=' || op === '==') op = '===';
        else if (op === '!=' || op === '«»') op = '!==';
        else if (op === '«') op = '<';
        else if (op === '«=' || op === '«=»') op = '<=';
        else if (op === '»') op = '>';
        else if (op === '»=' || op === '»=»') op = '>=';
        else if (op === 'AND') op = '&&';
        else if (op === 'OR') op = '||';
        if (op === '&&' || op === '||') {
          return `Boolean(${left} ${op} ${right})`;
        }
        return `(${left} ${op} ${right})`;
      }
      case 'IRUnaryOp':
      case 'UnaryExpression': {
        const operand = this.exprToJs(expr.operand || expr.argument, _preferLocal, preferEmptyFallback);
        if (expr.operator === 'NOT' || expr.operator === '!') {
          return `(!Boolean(${operand}))`;
        }
        if (expr.operator === '-') {
          return `(-Number(${operand}))`;
        }
        if (expr.operator === '+') {
          return `(+Number(${operand}))`;
        }
        return `(${expr.operator}${operand})`;
      }
      case 'IRActionCall':
      case 'CallExpression': {
        const argsJs = (expr.arguments || expr.args || [])
          .map((a: any) => this.exprToJs(a, _preferLocal, preferEmptyFallback))
          .join(', ');
        return `__manifest.callAction(${JSON.stringify(expr.actionName)}, [${argsJs}])`;
      }
      case 'IRIndexAccess':
      case 'IndexAccess': {
        const targetJs = this.exprToJs(expr.target, _preferLocal, preferEmptyFallback);
        const indexJs = this.exprToJs(expr.index, _preferLocal, preferEmptyFallback);
        return `__manifest.index(${targetJs}, ${indexJs})`;
      }
      case 'IRArray':
      case 'ArrayLiteral':
        return `[${(expr.elements || []).map((e: any) => this.exprToJs(e, _preferLocal, preferEmptyFallback)).join(', ')}]`;
      default:
        return JSON.stringify(expr);
    }
  }
