import {
  TargetCompiler,
  CompilationResult,
  TargetCompilerOptions,
  GeneratedArtifact,
} from '../compiler-interface.ts';
import { IRProgramNode, IRNode, IRInstructionNode } from '../../ir/ir.ts';

export class JSTargetCompiler implements TargetCompiler {
  public readonly targetName = 'js';
  public readonly fileExtension = 'js';

  public compile(ir: IRProgramNode, options: TargetCompilerOptions = {}): CompilationResult {
    const artifacts: GeneratedArtifact[] = [];
    const lines: string[] = [];

    lines.push(`// Generated by Manifest Compiler for ${ir.appName || 'App'}`);
    lines.push(`export const __manifest = {`);
    lines.push(`  state: {},`);
    lines.push(`  routes: {},`);
    lines.push(`  pages: {},`);
    lines.push(`  components: {},`);
    lines.push(`  listeners: [],`);
    lines.push(`  registerPage(name, renderFn) {`);
    lines.push(`    this.pages[name] = renderFn;`);
    lines.push(`  },`);
    lines.push(`  registerRoute(path, pageName) {`);
    lines.push(`    this.routes[path] = pageName;`);
    lines.push(`  },`);
    lines.push(`  registerComponent(name, renderFn) {`);
    lines.push(`    this.components[name] = renderFn;`);
    lines.push(`  },`);
    lines.push(`  notifyState() {`);
    lines.push(`    for (const listener of this.listeners) {`);
    lines.push(`      if (typeof listener === 'function') {`);
    lines.push(`        try { listener({ ...this.state }); } catch (e) {}`);
    lines.push(`      }`);
    lines.push(`    }`);
    lines.push(`  },`);
    lines.push(`  output(val) {`);
    lines.push(`    console.log(val);`);
    lines.push(`  },`);
    lines.push(`};`);
    lines.push('');

    // State initialization
    for (const s of (ir.state || [])) {
      lines.push(`__manifest.state["${s.name}"] = ${this.exprToJs(s.initialValue)};`);
    }

    // Top-level variables
    for (const v of (ir.variables || [])) {
      lines.push(`__manifest.state["${v.name}"] = ${this.exprToJs(v.initialValue)};`);
    }

    // Route registration
    for (const r of (ir.routes || [])) {
      const target = r.targetPage || r.pageName;
      lines.push(`__manifest.registerRoute("${r.path}", "${target}");`);
    }
    lines.push('');

    // Components registration
    const compList = (ir as any).components || [];
    for (const comp of compList) {
      lines.push(`__manifest.registerComponent("${comp.name}", (parent, props = {}) => {`);
      lines.push(`  const compDiv = document.createElement('div');`);
      lines.push(`  compDiv.className = 'manifest-component manifest-component-${comp.name.toLowerCase()}';`);
      this.generateNodes(comp.children || comp.body || [], 'compDiv', lines);
      lines.push(`  if (parent && parent.appendChild) parent.appendChild(compDiv);`);
      lines.push(`  return compDiv;`);
      lines.push(`});`);
    }

    // Pages registration
    // Pages registration
    for (const page of (ir.pages || [])) {
      lines.push(`__manifest.registerPage("${page.name}", (container) => {`);
      lines.push(`  if (container) {`);
      lines.push(`    container.className = 'manifest-page manifest-page-${page.name.toLowerCase()}';`);
      lines.push(`    if (container.style) {`);
      lines.push(`      container.style.minHeight = '100vh';`);
      lines.push(`      container.style.width = '100%';`);
      lines.push(`      container.style.display = 'flex';`);
      lines.push(`      container.style.flexDirection = 'column';`);
      lines.push(`    }`);
      lines.push(`  }`);
      this.applyStyles('container', page.styles, lines);
      if (page.styles?.background) {
        lines.push(`  if (typeof document !== 'undefined' && document.body) { document.body.style.background = "${page.styles.background}"; }`);
      } else if (page.styles?.backgroundColor) {
        lines.push(`  if (typeof document !== 'undefined' && document.body) { document.body.style.backgroundColor = "${page.styles.backgroundColor}"; }`);
      }
      this.generateNodes(page.children, 'container', lines);
      lines.push(`});`);
    }
    lines.push('');

    // startApp export function
    lines.push(`export async function startApp(targetOrOptions = {}, maybeOptions) {`);
    lines.push(`  let mountElement = null;`);
    lines.push(`  let opts = {};`);
    lines.push(`  if (typeof Element !== 'undefined' && targetOrOptions instanceof Element) {`);
    lines.push(`    mountElement = targetOrOptions;`);
    lines.push(`    if (maybeOptions && typeof maybeOptions === 'object') {`);
    lines.push(`      opts = maybeOptions;`);
    lines.push(`    } else if (typeof maybeOptions === 'function') {`);
    lines.push(`      opts = { onState: maybeOptions };`);
    lines.push(`    }`);
    lines.push(`  } else if (targetOrOptions && typeof targetOrOptions === 'object') {`);
    lines.push(`    opts = targetOrOptions;`);
    lines.push(`    mountElement = opts.mountElement || null;`);
    lines.push(`  }`);
    lines.push(`  const onStateChange = opts.onState || opts.onStateChange || (typeof arguments[1] === 'function' ? arguments[1] : null);`);
    lines.push(`  if (typeof onStateChange === 'function') {`);
    lines.push(`    __manifest.listeners.push(onStateChange);`);
    lines.push(`  }`);
    lines.push(`  const onOutputMsg = opts.onOutput || null;`);
    lines.push(`  if (typeof onOutputMsg === 'function') {`);
    lines.push(`    const origOutput = __manifest.output;`);
    lines.push(`    __manifest.output = (val) => {`);
    lines.push(`      origOutput(val);`);
    lines.push(`      try { onOutputMsg(val); } catch (_) {}`);
    lines.push(`    };`);
    lines.push(`  }`);
    lines.push('');

    // CSS Styling Injection
    lines.push(`  const styleTag = document.createElement('style');`);
    lines.push(`  styleTag.id = 'manifest-default-styles';`);
    lines.push(`  styleTag.textContent = \`
    .manifest-root { font-family: system-ui, sans-serif; padding: 1.5rem; color: #f3f4f6; }
    .manifest-page { display: flex; flex-direction: column; gap: 1rem; }
    .manifest-text { font-size: 1rem; color: #e5e7eb; }
    .manifest-button { padding: 0.5rem 1rem; border-radius: 0.375rem; background: #2563eb; color: #fff; cursor: pointer; border: none; font-weight: 500; transition: background 0.15s; }
    .manifest-button:hover { background: #1d4ed8; }
    .manifest-input { padding: 0.5rem; border-radius: 0.375rem; border: 1px solid #374151; background: #1f2937; color: #fff; }
    .manifest-container { display: flex; flex-direction: column; gap: 1rem; }
    .manifest-card { padding: 1.25rem; border-radius: 0.5rem; background: #1f2937; border: 1px solid #374151; }
    .manifest-list { display: flex; flex-direction: column; gap: 0.5rem; }
    .manifest-link { color: #60a5fa; text-decoration: underline; }
    .manifest-select { padding: 0.5rem; border-radius: 0.375rem; background: #1f2937; color: #fff; border: 1px solid #374151; }
    .manifest-textarea { padding: 0.5rem; border-radius: 0.375rem; background: #1f2937; color: #fff; border: 1px solid #374151; }
    header { padding: 1rem 0; border-bottom: 1px solid #374151; }
    nav { display: flex; gap: 1rem; }
    footer { padding: 1rem 0; border-top: 1px solid #374151; margin-top: auto; }
  \`;`);
    lines.push(`  if (typeof document !== 'undefined' && document.head && document.head.appendChild) {`);
    lines.push(`    document.head.appendChild(styleTag);`);
    lines.push(`  } else if (mountElement && mountElement.appendChild) {`);
    lines.push(`    mountElement.appendChild(styleTag);`);
    lines.push(`  }`);
    lines.push('');

    // DOM rendering root container
    lines.push(`  const rootDiv = document.createElement('div');`);
    lines.push(`  rootDiv.className = 'manifest-root';`);
    lines.push('');

    // Mount Active Page (Requirement J: do not append multiple pages simultaneously)
    lines.push(`  const pageKeys = Object.keys(__manifest.pages);`);
    lines.push(`  if (pageKeys.length > 0) {`);
    lines.push(`    const initialPageName = __manifest.routes['/'] || pageKeys[0];`);
    lines.push(`    const pageDiv = document.createElement('div');`);
    lines.push(`    pageDiv.id = 'manifest-active-page';`);
    lines.push(`    rootDiv.appendChild(pageDiv);`);
    lines.push(`    __manifest.activePage = initialPageName;`);
    lines.push(`    __manifest.renderActivePage = (pageName) => {`);
    lines.push(`      const renderFn = __manifest.pages[pageName] || __manifest.pages[pageKeys[0]];`);
    lines.push(`      if (renderFn) {`);
    lines.push(`        __manifest.activePage = pageName;`);
    lines.push(`        renderFn(pageDiv);`);
    lines.push(`      }`);
    lines.push(`    };`);
    lines.push(`    __manifest.navigateTo = (pathOrName) => {`);
    lines.push(`      const targetPage = __manifest.routes[pathOrName] || pathOrName;`);
    lines.push(`      if (__manifest.pages[targetPage]) {`);
    lines.push(`        __manifest.renderActivePage(targetPage);`);
    lines.push(`        __manifest.notifyState();`);
    lines.push(`      }`);
    lines.push(`    };`);
    lines.push(`    __manifest.renderActivePage(initialPageName);`);
    lines.push(`  }`);

    // If top-level UI nodes exist without pages
    if (ir.uiNodes && ir.uiNodes.length > 0) {
      this.generateNodes(ir.uiNodes, 'rootDiv', lines);
    }

    // Event handlers (e.g. app.starts)
    const eventList = (ir as any).events || (ir as any).eventHandlers || [];
    for (const ev of eventList) {
      const evName = ev.eventName || ev.event || ev.name;
      if (evName === 'app.starts' || evName === 'starts') {
        const instList = ev.instructions || ev.body || [];
        for (const inst of instList) {
          if (inst.type === 'IRShow' || inst.kind === 'IRShow' || inst.type === 'ShowStatement') {
            const outVal = inst.expression || inst.value;
            lines.push(`  __manifest.output(${this.exprToJs(outVal)});`);
          }
        }
      }
    }

    lines.push('');
    lines.push(`  if (mountElement && mountElement.appendChild) {`);
    lines.push(`    mountElement.innerHTML = '';`);
    lines.push(`    mountElement.appendChild(rootDiv);`);
    lines.push(`  }`);
    lines.push('');
    lines.push(`  __manifest.notifyState();`);
    lines.push(`  return __manifest;`);
    lines.push(`}`);

    const outputCode = lines.join('\n');
    const rawName = ir.appName ? ir.appName.toLowerCase().replace(/[^a-z0-9]/g, '') : 'app';
    const fileName = `${rawName}.js`;

    artifacts.push({
      fileName,
      content: outputCode,
      fileType: 'text',
    });

    return {
      success: true,
      target: 'js',
      outputCode,
      artifacts,
      diagnostics: [],
      ir,
    };
  }

  private generateNodes(nodes: any[], parentVar: string, lines: string[]): void {
    for (let i = 0; i < nodes.length; i++) {
      const node = nodes[i];
      const nodeVar = `node_${Math.random().toString(36).substring(2, 8)}`;
      const nodeKind = node.kind || node.type;

      switch (nodeKind) {
        case 'IRText':
        case 'Text': {
          lines.push(`  const ${nodeVar} = document.createElement('div');`);
          lines.push(`  ${nodeVar}.className = 'manifest-text';`);
          const textExpr = node.expression || node.content;
          lines.push(`  const update_${nodeVar} = () => {`);
          lines.push(`    ${nodeVar}.textContent = String(${this.exprToJs(textExpr, false, '', true)});`);
          lines.push(`  };`);
          lines.push(`  update_${nodeVar}();`);
          lines.push(`  __manifest.listeners.push(update_${nodeVar});`);
          this.applyStyles(nodeVar, node.styles, lines);
          lines.push(`  ${parentVar}.appendChild(${nodeVar});`);
          break;
        }
        case 'IRButton':
        case 'Button': {
          lines.push(`  const ${nodeVar} = document.createElement('button');`);
          lines.push(`  ${nodeVar}.className = 'manifest-button';`);
          lines.push(`  ${nodeVar}.textContent = String(${this.exprToJs(node.label)});`);
          this.applyStyles(nodeVar, node.styles, lines);
          lines.push(`  if (${nodeVar}.addEventListener) {`);
          lines.push(`    ${nodeVar}.addEventListener('mouseenter', () => { if (${nodeVar}.style) ${nodeVar}.style.filter = 'brightness(1.1)'; });`);
          lines.push(`    ${nodeVar}.addEventListener('mouseleave', () => { if (${nodeVar}.style) ${nodeVar}.style.filter = 'none'; });`);
          lines.push(`  }`);
          lines.push(`  ${nodeVar}.onclick = async (e) => {`);
          lines.push(`    if (e && e.preventDefault) e.preventDefault();`);
          const handlers = node.eventHandlers || (node.onClick ? [{ body: node.onClick }] : []);
          this.generateInstructionStatements(handlers, lines);
          lines.push(`    __manifest.notifyState();`);
          lines.push(`  };`);
          lines.push(`  ${parentVar}.appendChild(${nodeVar});`);
          break;
        }
        case 'IRInput':
        case 'Input': {
          lines.push(`  const ${nodeVar} = document.createElement('input');`);
          lines.push(`  ${nodeVar}.className = 'manifest-input';`);
          if (node.placeholder) {
            lines.push(`  ${nodeVar}.placeholder = String(${this.exprToJs(node.placeholder)});`);
          }
          if (node.bindVariable) {
            lines.push(`  ${nodeVar}.value = __manifest.state["${node.bindVariable}"] !== undefined ? __manifest.state["${node.bindVariable}"] : "";`);
            lines.push(`  const updateInput_${nodeVar} = () => {`);
            lines.push(`    if (typeof document !== 'undefined' && document.activeElement !== ${nodeVar}) {`);
            lines.push(`      ${nodeVar}.value = __manifest.state["${node.bindVariable}"] !== undefined ? __manifest.state["${node.bindVariable}"] : "";`);
            lines.push(`    }`);
            lines.push(`  };`);
            lines.push(`  __manifest.listeners.push(updateInput_${nodeVar});`);
          }
          lines.push(`  ${nodeVar}.oninput = (e) => {`);
          if (node.bindVariable) {
            lines.push(`    __manifest.state["${node.bindVariable}"] = e.target.value;`);
          }
          lines.push(`    __manifest.notifyState();`);
          lines.push(`  };`);
          this.applyStyles(nodeVar, node.styles, lines);
          lines.push(`  ${parentVar}.appendChild(${nodeVar});`);
          break;
        }
        case 'IRForm':
        case 'Form': {
          lines.push(`  const ${nodeVar} = document.createElement('form');`);
          lines.push(`  ${nodeVar}.className = 'manifest-form';`);
          lines.push(`  ${nodeVar}.onsubmit = async (e) => {`);
          lines.push(`    if (e && e.preventDefault) e.preventDefault();`);
          const formHandlers = node.eventHandlers || (node.onSubmit ? [{ body: node.onSubmit }] : []);
          this.generateInstructionStatements(formHandlers, lines);
          lines.push(`    __manifest.notifyState();`);
          lines.push(`  };`);
          this.applyStyles(nodeVar, node.styles, lines);
          this.generateNodes(node.children || [], nodeVar, lines);
          lines.push(`  ${parentVar}.appendChild(${nodeVar});`);
          break;
        }
        case 'IRContainer':
        case 'Container': {
          lines.push(`  const ${nodeVar} = document.createElement('div');`);
          lines.push(`  ${nodeVar}.className = "manifest-container";`);
          this.applyStyles(nodeVar, node.styles, lines);
          this.generateNodes(node.children || [], nodeVar, lines);
          lines.push(`  ${parentVar}.appendChild(${nodeVar});`);
          break;
        }
        case 'IRCard':
        case 'Card': {
          lines.push(`  const ${nodeVar} = document.createElement('div');`);
          lines.push(`  ${nodeVar}.className = "manifest-card";`);
          this.applyStyles(nodeVar, node.styles, lines);
          this.generateNodes(node.children || [], nodeVar, lines);
          lines.push(`  ${parentVar}.appendChild(${nodeVar});`);
          break;
        }
        case 'IRList':
        case 'List': {
          lines.push(`  const ${nodeVar} = document.createElement('div');`);
          lines.push(`  ${nodeVar}.className = "manifest-list";`);
          this.applyStyles(nodeVar, node.styles, lines);
          this.generateNodes(node.children || [], nodeVar, lines);
          lines.push(`  ${parentVar}.appendChild(${nodeVar});`);
          break;
        }
        case 'IRLink':
        case 'Link': {
          lines.push(`  const ${nodeVar} = document.createElement('a');`);
          lines.push(`  ${nodeVar}.className = "manifest-link";`);
          lines.push(`  ${nodeVar}.textContent = String(${this.exprToJs(node.label)});`);
          lines.push(`  ${nodeVar}.href = String(${this.exprToJs(node.target || node.href || '#')});`);
          this.applyStyles(nodeVar, node.styles, lines);
          lines.push(`  ${parentVar}.appendChild(${nodeVar});`);
          break;
        }
        case 'IRSelect':
        case 'Select': {
          lines.push(`  const ${nodeVar} = document.createElement('select');`);
          lines.push(`  ${nodeVar}.className = "manifest-select";`);
          for (const opt of (node.options || [])) {
            lines.push(`  { const optEl = document.createElement('option'); optEl.value = ${JSON.stringify(opt.value)}; optEl.textContent = ${JSON.stringify(opt.label || opt.value)}; ${nodeVar}.appendChild(optEl); }`);
          }
          if (node.bindVariable) {
            lines.push(`  ${nodeVar}.value = __manifest.state["${node.bindVariable}"] || '';`);
            lines.push(`  ${nodeVar}.onchange = (e) => {`);
            lines.push(`    __manifest.state["${node.bindVariable}"] = e.target.value;`);
            lines.push(`    __manifest.notifyState();`);
            lines.push(`  };`);
          }
          this.applyStyles(nodeVar, node.styles, lines);
          lines.push(`  ${parentVar}.appendChild(${nodeVar});`);
          break;
        }
        case 'IRCheckbox':
        case 'Checkbox': {
          lines.push(`  const __input = document.createElement('input');`);
          lines.push(`  __input.type = "checkbox";`);
          lines.push(`  __input.className = "manifest-checkbox";`);
          if (node.bindVariable) {
            lines.push(`  __input.checked = Boolean(__manifest.state["${node.bindVariable}"]);`);
          }
          lines.push(`  __input.onchange = (e) => {`);
          if (node.bindVariable) {
            lines.push(`    __manifest.state["${node.bindVariable}"] = e.target.checked;`);
          }
          lines.push(`    __manifest.notifyState();`);
          lines.push(`  };`);
          this.applyStyles('__input', node.styles, lines);
          lines.push(`  ${parentVar}.appendChild(__input);`);
          break;
        }
        case 'IRTextarea':
        case 'Textarea': {
          lines.push(`  const ${nodeVar} = document.createElement('textarea');`);
          lines.push(`  ${nodeVar}.className = "manifest-textarea";`);
          if (node.placeholder) lines.push(`  ${nodeVar}.placeholder = String(${this.exprToJs(node.placeholder)});`);
          if (node.bindVariable) {
            lines.push(`  ${nodeVar}.value = __manifest.state["${node.bindVariable}"] || '';`);
            lines.push(`  ${nodeVar}.oninput = (e) => {`);
            lines.push(`    __manifest.state["${node.bindVariable}"] = e.target.value;`);
            lines.push(`    __manifest.notifyState();`);
            lines.push(`  };`);
          }
          this.applyStyles(nodeVar, node.styles, lines);
          lines.push(`  ${parentVar}.appendChild(${nodeVar});`);
          break;
        }
        case 'IRHeader':
        case 'Header': {
          lines.push(`  const ${nodeVar} = document.createElement("header");`);
          this.applyStyles(nodeVar, node.styles, lines);
          this.generateNodes(node.children || [], nodeVar, lines);
          lines.push(`  ${parentVar}.appendChild(${nodeVar});`);
          break;
        }
        case 'IRNav':
        case 'Nav': {
          lines.push(`  const ${nodeVar} = document.createElement("nav");`);
          this.applyStyles(nodeVar, node.styles, lines);
          this.generateNodes(node.children || [], nodeVar, lines);
          lines.push(`  ${parentVar}.appendChild(${nodeVar});`);
          break;
        }
        case 'IRFooter':
        case 'Footer': {
          lines.push(`  const ${nodeVar} = document.createElement("footer");`);
          this.applyStyles(nodeVar, node.styles, lines);
          this.generateNodes(node.children || [], nodeVar, lines);
          lines.push(`  ${parentVar}.appendChild(${nodeVar});`);
          break;
        }
        case 'IRComponentCall':
        case 'ComponentCall': {
          const compName = node.componentName || node.name;
          lines.push(`  if (__manifest.components["${compName}"]) {`);
          lines.push(`    __manifest.components["${compName}"](${parentVar}, {});`);
          lines.push(`  }`);
          break;
        }
        default:
          break;
      }
    }
  }

  private generateInstructionStatements(handlers: any[], lines: string[]): void {
    for (const h of (handlers || [])) {
      const instList = h.body || h.instructions || [];
      for (const inst of instList) {
        const instKind = inst.kind || inst.type;
        if (instKind === 'IRAssignment' || instKind === 'IRSet' || instKind === 'SetStatement') {
          const target = inst.target || inst.variable;
          const valExpr = inst.value || inst.expression;
          const exprStr = this.exprToJs(valExpr, true, target);
          lines.push(`    let ${target} = __manifest.state["${target}"] !== undefined ? __manifest.state["${target}"] : 0;`);
          lines.push(`    ${target} = ${exprStr};`);
          lines.push(`    __manifest.state["${target}"] = ${target};`);
        } else if (instKind === 'IRShow' || instKind === 'ShowStatement') {
          lines.push(`    __manifest.output(String(${this.exprToJs(inst.expression || inst.value)}));`);
        }
      }
    }
  }

  private applyStyles(elementVar: string, styles: Record<string, string | number> | undefined, lines: string[]): void {
    if (!styles) return;
    for (const [rawKey, val] of Object.entries(styles)) {
      const kebab = rawKey.replace(/[A-Z]/g, (m) => `-${m.toLowerCase()}`).replace(/_/g, '-').toLowerCase();
      const camel = kebab.replace(/-([a-z])/g, (_, g) => g.toUpperCase());
      const safeVal = String(val).replace(/"/g, '\\"');
      lines.push(`  if (${elementVar} && ${elementVar}.style) {`);
      lines.push(`    try { ${elementVar}.style.setProperty("${kebab}", "${safeVal}"); } catch (_) {}`);
      lines.push(`    try { ${elementVar}.style["${camel}"] = "${safeVal}"; } catch (_) {}`);
      lines.push(`  }`);
    }
  }

  private exprToJs(expr: any, inAssignment = false, targetVar = '', preferState = false): string {
    if (expr === null || expr === undefined) return '""';
    if (typeof expr === 'string' || typeof expr === 'number' || typeof expr === 'boolean') {
      return JSON.stringify(expr);
    }
    const kind = expr.kind || expr.type;
    switch (kind) {
      case 'IRLiteral':
      case 'Literal':
        return JSON.stringify(expr.value);
      case 'IRVariableRef':
      case 'Identifier': {
        const varName = expr.name;
        if (inAssignment) {
          return varName;
        }
        if (preferState) {
          return `(__manifest.state["${varName}"] !== undefined ? __manifest.state["${varName}"] : (typeof ${varName} !== 'undefined' ? ${varName} : ""))`;
        }
        return `(__manifest.state["${varName}"] !== undefined ? __manifest.state["${varName}"] : (typeof ${varName} !== 'undefined' ? ${varName} : ${JSON.stringify(varName)}))`;
      }
      case 'IRBinaryOp':
      case 'BinaryExpression': {
        const left = this.exprToJs(expr.left, inAssignment, targetVar, preferState);
        const right = this.exprToJs(expr.right, inAssignment, targetVar, preferState);
        let op = expr.operator;
        if (op === '=' || op === '==') op = '===';
        else if (op === '!=' || op === '«»') op = '!==';
        else if (op === '«') op = '<';
        else if (op === '«=') op = '<=';
        else if (op === '»') op = '>';
        else if (op === '»=') op = '>=';
        else if (op === 'AND') op = '&&';
        else if (op === 'OR') op = '||';
        return `(${left} ${op} ${right})`;
      }
      case 'IRUnaryOp':
      case 'UnaryExpression': {
        const operand = this.exprToJs(expr.operand || expr.argument, inAssignment, targetVar, preferState);
        return `(${expr.operator}${operand})`;
      }
      case 'IRArray':
      case 'ArrayLiteral':
        return `[${(expr.elements || []).map((e: any) => this.exprToJs(e, inAssignment, targetVar, preferState)).join(', ')}]`;
      default:
        return JSON.stringify(expr);
    }
  }
}

export const JavaScriptTargetCompiler = JSTargetCompiler;
export type JavaScriptTargetCompiler = JSTargetCompiler;
