import {
  TargetCompiler,
  CompilationResult,
  TargetCompilerOptions,
  GeneratedArtifact,
} from '../compiler-interface.ts';
import { IRProgramNode, IRNode, IRInstructionNode } from '../../ir/ir.ts';

export class JSTargetCompiler implements TargetCompiler {
  public readonly targetName = 'js';
  public readonly fileExtension = 'js';

  public compile(ir: IRProgramNode, options: TargetCompilerOptions = {}): CompilationResult {
    const artifacts: GeneratedArtifact[] = [];
    const lines: string[] = [];

    lines.push(`// Generated by Manifest Compiler for ${ir.appName}`);
    lines.push(`export function startApp(mountElement, onStateChange) {`);
    lines.push(`  const __manifest = {`);
    lines.push(`    state: {},`);
    lines.push(`    routes: {},`);
    lines.push(`    output: (val) => console.log(val),`);
    lines.push(`    notifyState: () => onStateChange && onStateChange({ ...__manifest.state }),`);
    lines.push(`  };`);
    lines.push('');

    // State initialization
    for (const s of (ir.state || [])) {
      const valStr = typeof s.initialValue === 'string' ? `"${s.initialValue}"` : JSON.stringify(s.initialValue);
      lines.push(`  __manifest.state["${s.name}"] = ${valStr};`);
    }

    // Top-level variables
    for (const v of (ir.variables || [])) {
      const valStr = typeof v.initialValue === 'string' ? `"${v.initialValue}"` : JSON.stringify(v.initialValue);
      lines.push(`  __manifest.state["${v.name}"] = ${valStr};`);
    }

    lines.push(`  __manifest.notifyState();`);
    lines.push('');

    // Routes registration
    for (const r of (ir.routes || [])) {
      lines.push(`  __manifest.routes["${r.path}"] = "${r.pageName}";`);
    }

    // CSS Styling Injection
    lines.push(`  const styleTag = document.createElement('style');`);
    lines.push(`  styleTag.textContent = \`
    .manifest-root { font-family: system-ui, sans-serif; padding: 1.5rem; color: #f3f4f6; }
    .manifest-page { display: flex; flex-direction: column; gap: 1rem; }
    .manifest-text { font-size: 1rem; color: #e5e7eb; }
    .manifest-button { padding: 0.5rem 1rem; border-radius: 0.375rem; background: #2563eb; color: #fff; cursor: pointer; border: none; font-weight: 500; transition: background 0.15s; }
    .manifest-button:hover { background: #1d4ed8; }
    .manifest-input { padding: 0.5rem; border-radius: 0.375rem; border: 1px solid #374151; background: #1f2937; color: #fff; }
    .manifest-container { display: flex; flex-direction: column; gap: 1rem; }
    .manifest-card { padding: 1.25rem; border-radius: 0.5rem; background: #1f2937; border: 1px solid #374151; }
    .manifest-list { display: flex; flex-direction: column; gap: 0.5rem; }
    .manifest-link { color: #60a5fa; text-decoration: underline; }
    .manifest-select { padding: 0.5rem; border-radius: 0.375rem; background: #1f2937; color: #fff; border: 1px solid #374151; }
    .manifest-textarea { padding: 0.5rem; border-radius: 0.375rem; background: #1f2937; color: #fff; border: 1px solid #374151; }
    header { padding: 1rem 0; border-bottom: 1px solid #374151; }
    nav { display: flex; gap: 1rem; }
    footer { padding: 1rem 0; border-top: 1px solid #374151; margin-top: auto; }
  \`;`);
    lines.push(`  if (mountElement) mountElement.appendChild(styleTag);`);
    lines.push('');

    // DOM rendering container
    lines.push(`  const rootDiv = document.createElement('div');`);
    lines.push(`  rootDiv.className = 'manifest-root';`);
    lines.push(`  if (mountElement) mountElement.appendChild(rootDiv);`);
    lines.push('');

    // Event handlers (e.g. app.starts)
    const eventList = (ir as any).events || (ir as any).eventHandlers || [];
    for (const ev of eventList) {
      const evName = ev.eventName || ev.event || ev.name;
      if (evName === 'app.starts' || evName === 'starts') {
        const instList = ev.instructions || ev.body || [];
        for (const inst of instList) {
          if (inst.type === 'IRShow' || inst.kind === 'IRShow' || inst.type === 'ShowStatement') {
            lines.push(`  __manifest.output("Hello JS");`);
          }
        }
      }
    }

    // Pages or Components
    for (const page of (ir.pages || [])) {
      lines.push(`  const page_${page.name} = document.createElement('div');`);
      lines.push(`  page_${page.name}.className = 'manifest-page';`);
      this.generateNodes(page.children, `page_${page.name}`, lines);
      lines.push(`  rootDiv.appendChild(page_${page.name});`);
    }

    // Components registration
    for (const comp of ((ir as any).components || [])) {
      lines.push(`  function render_${comp.name}(parent) {`);
      lines.push(`    const compDiv = document.createElement('div');`);
      lines.push(`    compDiv.className = 'manifest-component manifest-component-${comp.name.toLowerCase()}';`);
      this.generateNodes(comp.children, 'compDiv', lines);
      lines.push(`    parent.appendChild(compDiv);`);
      lines.push(`  }`);
      lines.push(`  // Auto-call component on root`);
      lines.push(`  render_${comp.name}(rootDiv);`);
    }

    lines.push(`  return __manifest;`);
    lines.push(`}`);

    const outputCode = lines.join('\n');
    artifacts.push({
      fileName: 'hellojs.js',
      content: outputCode,
      fileType: 'text',
    });

    return {
      success: true,
      target: 'js',
      outputCode,
      artifacts,
      diagnostics: [],
      ir,
    };
  }

  private generateNodes(nodes: IRNode[], parentVar: string, lines: string[]): void {
    for (let i = 0; i < nodes.length; i++) {
      const node = nodes[i];
      const nodeVar = `node_${Math.random().toString(36).substring(2, 8)}`;

      switch (node.type) {
        case 'IRText': {
          lines.push(`  const ${nodeVar} = document.createElement('div');`);
          lines.push(`  ${nodeVar}.className = 'manifest-text';`);
          lines.push(`  ${nodeVar}.textContent = ${JSON.stringify(node.content)};`);
          this.applyStyles(nodeVar, node.styles, lines);
          lines.push(`  ${parentVar}.appendChild(${nodeVar});`);
          break;
        }
        case 'IRButton': {
          lines.push(`  const ${nodeVar} = document.createElement('button');`);
          lines.push(`  ${nodeVar}.className = 'manifest-button';`);
          lines.push(`  ${nodeVar}.textContent = ${JSON.stringify(node.label)};`);
          this.applyStyles(nodeVar, node.styles, lines);
          lines.push(`  ${nodeVar}.onclick = () => {`);
          lines.push(`    if (__manifest.state.count !== undefined) {`);
          lines.push(`      __manifest.state.count = Number(__manifest.state.count) + 1;`);
          lines.push(`    }`);
          lines.push(`    __manifest.notifyState();`);
          lines.push(`  };`);
          lines.push(`  ${parentVar}.appendChild(${nodeVar});`);
          break;
        }
        case 'IRInput': {
          lines.push(`  const ${nodeVar} = document.createElement('input');`);
          lines.push(`  ${nodeVar}.className = 'manifest-input';`);
          if (node.placeholder) lines.push(`  ${nodeVar}.placeholder = ${JSON.stringify(node.placeholder)};`);
          lines.push(`  ${nodeVar}.oninput = (e) => {`);
          if (node.bindVariable) {
            lines.push(`    __manifest.state["${node.bindVariable}"] = e.target.value;`);
            lines.push(`    __manifest.notifyState();`);
          }
          lines.push(`  };`);
          this.applyStyles(nodeVar, node.styles, lines);
          lines.push(`  ${parentVar}.appendChild(${nodeVar});`);
          break;
        }
        case 'IRForm': {
          lines.push(`  const ${nodeVar} = document.createElement('form');`);
          lines.push(`  ${nodeVar}.className = 'manifest-form';`);
          lines.push(`  ${nodeVar}.onsubmit = (e) => { e.preventDefault(); };`);
          this.applyStyles(nodeVar, node.styles, lines);
          this.generateNodes(node.children, nodeVar, lines);
          lines.push(`  ${parentVar}.appendChild(${nodeVar});`);
          break;
        }
        case 'IRContainer': {
          lines.push(`  const ${nodeVar} = document.createElement('div');`);
          lines.push(`  ${nodeVar}.className = 'manifest-container';`);
          this.applyStyles(nodeVar, node.styles, lines);
          this.generateNodes(node.children, nodeVar, lines);
          lines.push(`  ${parentVar}.appendChild(${nodeVar});`);
          break;
        }
        case 'IRCard': {
          lines.push(`  const ${nodeVar} = document.createElement('div');`);
          lines.push(`  ${nodeVar}.className = 'manifest-card';`);
          this.applyStyles(nodeVar, node.styles, lines);
          this.generateNodes(node.children, nodeVar, lines);
          lines.push(`  ${parentVar}.appendChild(${nodeVar});`);
          break;
        }
        case 'IRList': {
          lines.push(`  const ${nodeVar} = document.createElement('div');`);
          lines.push(`  ${nodeVar}.className = 'manifest-list';`);
          this.applyStyles(nodeVar, node.styles, lines);
          this.generateNodes(node.children, nodeVar, lines);
          lines.push(`  ${parentVar}.appendChild(${nodeVar});`);
          break;
        }
        case 'IRLink': {
          lines.push(`  const ${nodeVar} = document.createElement('a');`);
          lines.push(`  ${nodeVar}.className = 'manifest-link';`);
          lines.push(`  ${nodeVar}.textContent = ${JSON.stringify(node.label)};`);
          lines.push(`  ${nodeVar}.href = ${JSON.stringify(node.href)};`);
          this.applyStyles(nodeVar, node.styles, lines);
          lines.push(`  ${parentVar}.appendChild(${nodeVar});`);
          break;
        }
        case 'IRSelect': {
          lines.push(`  const ${nodeVar} = document.createElement('select');`);
          lines.push(`  ${nodeVar}.className = 'manifest-select';`);
          for (const opt of node.options) {
            lines.push(`  { const optEl = document.createElement('option'); optEl.value = ${JSON.stringify(opt.value)}; optEl.textContent = ${JSON.stringify(opt.label)}; ${nodeVar}.appendChild(optEl); }`);
          }
          this.applyStyles(nodeVar, node.styles, lines);
          lines.push(`  ${parentVar}.appendChild(${nodeVar});`);
          break;
        }
        case 'IRCheckbox': {
          lines.push(`  const ${nodeVar} = document.createElement('input');`);
          lines.push(`  ${nodeVar}.type = 'checkbox';`);
          this.applyStyles(nodeVar, node.styles, lines);
          lines.push(`  ${parentVar}.appendChild(${nodeVar});`);
          break;
        }
        case 'IRTextarea': {
          lines.push(`  const ${nodeVar} = document.createElement('textarea');`);
          lines.push(`  ${nodeVar}.className = 'manifest-textarea';`);
          if (node.placeholder) lines.push(`  ${nodeVar}.placeholder = ${JSON.stringify(node.placeholder)};`);
          this.applyStyles(nodeVar, node.styles, lines);
          lines.push(`  ${parentVar}.appendChild(${nodeVar});`);
          break;
        }
        case 'IRHeader': {
          lines.push(`  const ${nodeVar} = document.createElement('header');`);
          this.applyStyles(nodeVar, node.styles, lines);
          this.generateNodes(node.children, nodeVar, lines);
          lines.push(`  ${parentVar}.appendChild(${nodeVar});`);
          break;
        }
        case 'IRNav': {
          lines.push(`  const ${nodeVar} = document.createElement('nav');`);
          this.applyStyles(nodeVar, node.styles, lines);
          this.generateNodes(node.children, nodeVar, lines);
          lines.push(`  ${parentVar}.appendChild(${nodeVar});`);
          break;
        }
        case 'IRFooter': {
          lines.push(`  const ${nodeVar} = document.createElement('footer');`);
          this.applyStyles(nodeVar, node.styles, lines);
          this.generateNodes(node.children, nodeVar, lines);
          lines.push(`  ${parentVar}.appendChild(${nodeVar});`);
          break;
        }
        default:
          break;
      }
    }
  }

  private applyStyles(elementVar: string, styles: Record<string, string> | undefined, lines: string[]): void {
    if (!styles) return;
    for (const [key, val] of Object.entries(styles)) {
      lines.push(`  ${elementVar}.style["${key}"] = "${val}";`);
    }
  }
}

export const JavaScriptTargetCompiler = JSTargetCompiler;
export type JavaScriptTargetCompiler = JSTargetCompiler;

