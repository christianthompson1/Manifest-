import { MIRExpr, MIRFunction, MIRModule, MIRStmt } from '../ir/typed-ir.ts';
import { SemanticDiagnostic, SemanticType } from '../semantics/types.ts';

export interface NativeTargetResult {
  success: boolean;
  rustSource: string;
  binaryCompiled: boolean;
  binaryPath?: string;
  binarySizeBytes?: number;
  toolchainStatus: 'compiled-with-rustc' | 'requires-host-rustc';
  toolchainVersion?: string;
  diagnostics: SemanticDiagnostic[];
}

function mapRustType(t: SemanticType): string {
  switch (t.kind) {
    case 'i64':
      return 'i64';
    case 'f64':
      return 'f64';
    case 'bool':
      return 'bool';
    case 'str':
      return 'String';
    case 'void':
    case 'any':
      return '()';
    case 'array':
      return `Vec<${mapRustType(t.element)}>`;
    case 'map':
      return `std::collections::BTreeMap<String, ${mapRustType(t.value)}>`;
    case 'struct':
      return `M_${sanitizeRustIdent(t.name)}`;
    case 'enum':
      return `M_${sanitizeRustIdent(t.name)}`;
    case 'result':
      return `Result<${mapRustType(t.ok)}, ${mapRustType(t.err)}>`;
    default:
      return 'i64';
  }
}

function sanitizeRustIdent(s: string): string {
  return s.replace(/[^a-zA-Z0-9_]/g, '_');
}

/**
 * Generates standalone, zero-dependency, memory-safe Rust source from `MIRModule`.
 * When executed in a Node/CLI host with `rustc` installed, `compileNativeBinaryNode`
 * invokes `rustc -O` to emit a real OS native executable.
 */
export function emitStandaloneRustSource(mir: MIRModule): string {
  const lines: string[] = [];
  lines.push(`#![allow(non_snake_case, non_camel_case_types, unused_variables, unused_mut, dead_code)]`);
  lines.push(`// Generated by Manifest v1.0 Native Backend (MIR -> Standalone Safe Rust)`);
  lines.push(`// Module: ${mir.moduleName}`);
  lines.push(`// Capabilities Required: [${mir.requires.join(', ')}]`);
  lines.push(``);
  lines.push(`#[inline] fn m_add_i64(a: i64, b: i64) -> i64 { a.checked_add(b).expect("Manifest trap: checked i64 add overflow") }`);
  lines.push(`#[inline] fn m_sub_i64(a: i64, b: i64) -> i64 { a.checked_sub(b).expect("Manifest trap: checked i64 sub overflow") }`);
  lines.push(`#[inline] fn m_mul_i64(a: i64, b: i64) -> i64 { a.checked_mul(b).expect("Manifest trap: checked i64 mul overflow") }`);
  lines.push(`#[inline] fn m_div_i64(a: i64, b: i64) -> i64 { if b == 0 { panic!("Manifest trap: division by zero"); } a.checked_div(b).expect("Manifest trap: checked i64 div overflow") }`);
  lines.push(`#[inline] fn m_mod_i64(a: i64, b: i64) -> i64 { if b == 0 { panic!("Manifest trap: remainder by zero"); } a.checked_rem(b).expect("Manifest trap: checked i64 rem overflow") }`);
  lines.push(``);

  for (const st of mir.structs) {
    lines.push(`#[derive(Clone, Debug, PartialEq)]`);
    lines.push(`struct M_${sanitizeRustIdent(st.name)} {`);
    st.fields.forEach((f, idx) => {
      lines.push(`    f_${idx}: ${mapRustType(f.type)}, // ${f.name}`);
    });
    lines.push(`}`);
    lines.push(``);
  }

  for (const en of mir.enums) {
    if (en.name === 'Result') continue;
    lines.push(`#[derive(Clone, Debug, PartialEq)]`);
    lines.push(`enum M_${sanitizeRustIdent(en.name)} {`);
    for (const v of en.variants) {
      if (v.payloadTypes.length === 0) {
        lines.push(`    V_${v.tag}, // ${v.name}`);
      } else {
        lines.push(`    V_${v.tag}(${v.payloadTypes.map(mapRustType).join(', ')}), // ${v.name}`);
      }
    }
    lines.push(`}`);
    lines.push(``);
  }

  for (const fn of mir.functions) {
    if (fn.name === '__init__' && mir.globals.length === 0) continue;
    const params = fn.params
      .map((p) => `mut l_${p.slot}: ${mapRustType(p.type)}`)
      .join(', ');
    const concreteRet = resolveConcreteFnReturn(fn);
    const retType = mapRustType(concreteRet);
    lines.push(`fn m_fn_${sanitizeRustIdent(fn.name)}(${params}) -> ${retType} {`);
    for (let i = fn.params.length; i < fn.locals.length; i++) {
      const loc = fn.locals[i];
      const defaultInit = defaultRustValue(loc.type);
      lines.push(`    let mut l_${loc.slot}: ${mapRustType(loc.type)} = ${defaultInit};`);
    }
    for (const s of fn.body) {
      emitRustStmt(s, '    ', lines, concreteRet);
    }
    if (retType !== '()') {
      lines.push(`    ${defaultRustValue(concreteRet)}`);
    }
    lines.push(`}`);
    lines.push(``);
  }

  const entryFn = mir.functions.find((f) => f.name === mir.entryFunction) || mir.functions.find((f) => f.name === 'main');
  lines.push(`fn main() {`);
  if (entryFn) {
    const entryRet = resolveConcreteFnReturn(entryFn);
    if (entryRet.kind === 'void' || entryRet.kind === 'any') {
      lines.push(`    m_fn_${sanitizeRustIdent(entryFn.name)}();`);
    } else {
      lines.push(`    let __res = m_fn_${sanitizeRustIdent(entryFn.name)}();`);
      lines.push(`    println!("{:?}", __res);`);
    }
  }
  lines.push(`}`);

  return lines.join('\n');
}

function resolveConcreteFnReturn(fn: MIRFunction): SemanticType {
  if (fn.returnType.kind !== 'any') return fn.returnType;
  for (const s of fn.body) {
    if (s.kind === 'Return' && s.value && s.value.type.kind !== 'any') {
      return s.value.type;
    }
  }
  return { kind: 'void' };
}

function defaultRustValue(t: SemanticType): string {
  switch (t.kind) {
    case 'i64':
      return '0i64';
    case 'f64':
      return '0.0f64';
    case 'bool':
      return 'false';
    case 'str':
      return 'String::new()';
    case 'array':
      return 'Vec::new()';
    case 'map':
      return 'std::collections::BTreeMap::new()';
    case 'struct':
      return `M_${sanitizeRustIdent(t.name)} { ${t.fields.map((f, i) => `f_${i}: ${defaultRustValue(f.type)}`).join(', ')} }`;
    default:
      return '()';
  }
}

function emitRustStmt(stmt: MIRStmt, indent: string, out: string[], fnRet: SemanticType): void {
  switch (stmt.kind) {
    case 'StoreLocal':
      out.push(`${indent}l_${stmt.slot} = ${emitRustExpr(stmt.value)};`);
      break;
    case 'ArraySet':
      out.push(`${indent}${emitRustExpr(stmt.array)}[(${emitRustExpr(stmt.index)}) as usize] = ${emitRustExpr(stmt.value)};`);
      break;
    case 'FieldSet':
      out.push(`${indent}${emitRustExpr(stmt.object)}.f_${stmt.fieldIndex} = ${emitRustExpr(stmt.value)};`);
      break;
    case 'ExprStmt':
      out.push(`${indent}let _ = ${emitRustExpr(stmt.expr)};`);
      break;
    case 'If':
      out.push(`${indent}if ${emitRustExpr(stmt.condition)} {`);
      for (const s of stmt.thenBranch) emitRustStmt(s, indent + '    ', out, fnRet);
      if (stmt.elseBranch.length > 0) {
        out.push(`${indent}} else {`);
        for (const s of stmt.elseBranch) emitRustStmt(s, indent + '    ', out, fnRet);
      }
      out.push(`${indent}}`);
      break;
    case 'While':
      out.push(`${indent}while ${emitRustExpr(stmt.condition)} {`);
      for (const s of stmt.body) emitRustStmt(s, indent + '    ', out, fnRet);
      out.push(`${indent}}`);
      break;
    case 'Break':
      out.push(`${indent}break;`);
      break;
    case 'Continue':
      out.push(`${indent}continue;`);
      break;
    case 'Return':
      if (stmt.value && fnRet.kind !== 'void') {
        out.push(`${indent}return ${emitRustExpr(stmt.value)};`);
      } else {
        out.push(`${indent}return;`);
      }
      break;
    default:
      break;
  }
}

function emitRustExpr(expr: MIRExpr): string {
  switch (expr.kind) {
    case 'ConstInt':
      return `${expr.value}i64`;
    case 'ConstFloat':
      return Number.isInteger(expr.value) ? `${expr.value}.0f64` : `${expr.value}f64`;
    case 'ConstBool':
      return expr.value ? 'true' : 'false';
    case 'ConstStr':
      return `String::from(${JSON.stringify(expr.value)})`;
    case 'ConstVoid':
      return '()';
    case 'LoadLocal':
      return `l_${expr.slot}.clone()`;
    case 'LoadGlobal':
      return `0i64`;
    case 'Unary':
      if (expr.op === '-' && expr.operand.type.kind === 'i64') {
        return `(${emitRustExpr(expr.operand)}).checked_neg().expect("overflow")`;
      }
      return `(${expr.op}(${emitRustExpr(expr.operand)}))`;
    case 'Cast':
      if (expr.castKind === 'i64_to_f64') return `((${emitRustExpr(expr.operand)}) as f64)`;
      if (expr.castKind === 'f64_to_i64') return `((${emitRustExpr(expr.operand)}) as i64)`;
      return `format!("{}", ${emitRustExpr(expr.operand)})`;
    case 'Binary': {
      const l = emitRustExpr(expr.left);
      const r = emitRustExpr(expr.right);
      if (expr.type.kind === 'str' && expr.op === '+') {
        return `format!("{}{}", ${l}, ${r})`;
      }
      if (expr.left.type.kind === 'i64' && expr.right.type.kind === 'i64') {
        if (expr.op === '+') return `m_add_i64(${l}, ${r})`;
        if (expr.op === '-') return `m_sub_i64(${l}, ${r})`;
        if (expr.op === '*') return `m_mul_i64(${l}, ${r})`;
        if (expr.op === '/') return `m_div_i64(${l}, ${r})`;
        if (expr.op === '%') return `m_mod_i64(${l}, ${r})`;
      }
      return `(${l} ${expr.op} ${r})`;
    }
    case 'CallFunction':
      return `m_fn_${sanitizeRustIdent(expr.callee)}(${expr.args.map(emitRustExpr).join(', ')})`;
    case 'CallIntrinsic': {
      if (expr.symbol === 'console.print') {
        if (expr.args.length === 0) return `println!()`;
        const fmt = expr.args.map(() => '{}').join(' ');
        return `println!("${fmt}", ${expr.args.map(emitRustExpr).join(', ')})`;
      }
      if (expr.symbol === 'std::math::sqrt') return `(${emitRustExpr(expr.args[0])}).sqrt()`;
      if (expr.symbol === 'std::math::abs') return `(${emitRustExpr(expr.args[0])}).abs()`;
      if (expr.symbol === 'std::math::min') return `std::cmp::min(${emitRustExpr(expr.args[0])}, ${emitRustExpr(expr.args[1])})`;
      if (expr.symbol === 'std::math::max') return `std::cmp::max(${emitRustExpr(expr.args[0])}, ${emitRustExpr(expr.args[1])})`;
      return `()`;
    }
    case 'ArrayNew':
      return `vec![${expr.elements.map(emitRustExpr).join(', ')}]`;
    case 'ArrayGet':
      return `${emitRustExpr(expr.array)}[(${emitRustExpr(expr.index)}) as usize].clone()`;
    case 'ArrayLen':
      return `(${emitRustExpr(expr.target)}.len() as i64)`;
    case 'ArrayPush':
      return `${emitRustExpr(expr.array)}.push(${emitRustExpr(expr.value)})`;
    case 'StructNew':
      return `M_${sanitizeRustIdent(expr.structName)} { ${expr.fields.map((f, i) => `f_${i}: ${emitRustExpr(f)}`).join(', ')} }`;
    case 'FieldGet':
      return `${emitRustExpr(expr.object)}.f_${expr.fieldIndex}.clone()`;
    default:
      return `()`;
  }
}

/**
 * Browser-safe builder: emits standalone Rust codegen and reports honest toolchain status.
 */
export function buildNativeTargetSourceOnly(mir: MIRModule): NativeTargetResult {
  const rustSource = emitStandaloneRustSource(mir);
  return {
    success: true,
    rustSource,
    binaryCompiled: false,
    toolchainStatus: 'requires-host-rustc',
    diagnostics: [
      {
        code: 'I_NATIVE_REQUIRES_HOST_RUSTC',
        severity: 'info',
        message:
          'Standalone Rust source generated. Compiling a native machine executable requires running on a host OS with rustc installed (available via Manifest CLI).',
        line: 1,
        column: 1,
      },
    ],
  };
}
