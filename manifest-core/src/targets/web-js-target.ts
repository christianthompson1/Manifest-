import { MIRExpr, MIRFunction, MIRModule, MIRStmt } from '../ir/typed-ir.ts';

export interface WebJsBuildResult {
  jsCode: string;
  htmlPreview: string;
  enforcedCapabilities: {
    allowed: string[];
    denied: string[];
    networkBlocked: boolean;
  };
}

/**
 * Compiles general-purpose Typed Manifest IR (`MIRModule`) into a capability-restricted
 * ES JavaScript module + sandboxed HTML execution runner.
 *
 * Enforces checked 64-bit integer (`BigInt`) bounds and capability-gated host APIs
 * (for example, blocking `fetch` / `XMLHttpRequest` / `WebSocket` when `net` is denied
 * or omitted from `requires`).
 */
export function compileMIRToWebJS(mir: MIRModule): WebJsBuildResult {
  const networkAllowed =
    mir.requires.some((r) => r === 'net' || r.startsWith('net.')) &&
    !mir.denies.some((d) => d === 'net' || d.startsWith('net.'));

  const lines: string[] = [];
  lines.push(`// Generated by Manifest v1.0 Web/JS Compiler`);
  lines.push(`// Module: ${mir.moduleName} | Requires: [${mir.requires.join(', ')}] | Denies: [${mir.denies.join(', ')}]`);
  lines.push(`const __M_I64_MIN = -9223372036854775808n;`);
  lines.push(`const __M_I64_MAX = 9223372036854775807n;`);
  lines.push(`const __M_REQUIRES = new Set(${JSON.stringify(mir.requires)});`);
  lines.push(`const __M_DENIES = new Set(${JSON.stringify(mir.denies)});`);
  lines.push(`const __m_vfs = new Map();`);
  lines.push(`const __m_stdout = [];`);
  lines.push(``);

  if (!networkAllowed) {
    lines.push(`// Capability Guard: 'net' is not granted for this module`);
    lines.push(`const fetch = () => { throw new Error("CapabilityDenied: 'net' capability is not granted for module '${mir.moduleName}'"); };`);
    lines.push(`const XMLHttpRequest = function() { throw new Error("CapabilityDenied: 'net' capability is not granted"); };`);
    lines.push(`const WebSocket = function() { throw new Error("CapabilityDenied: 'net' capability is not granted"); };`);
    lines.push(``);
  }

  lines.push(`function __m_require_cap(cap, op) {`);
  lines.push(`  if (cap === 'pure') return;`);
  lines.push(`  for (const d of __M_DENIES) {`);
  lines.push(`    if (cap === d || cap.startsWith(d + '.')) throw new Error("CapabilityDenied: '" + cap + "' is explicitly denied (" + op + ")");`);
  lines.push(`  }`);
  lines.push(`  let ok = false;`);
  lines.push(`  for (const r of __M_REQUIRES) {`);
  lines.push(`    if (cap === r || cap.startsWith(r + '.')) { ok = true; break; }`);
  lines.push(`  }`);
  lines.push(`  if (!ok) throw new Error("CapabilityDenied: '" + cap + "' is not declared in module requires (" + op + ")");`);
  lines.push(`}`);
  lines.push(``);
  lines.push(`function __m_i64(v, op) {`);
  lines.push(`  if (v < __M_I64_MIN || v > __M_I64_MAX) throw new Error("IntegerOverflow: checked i64 overflow in " + op);`);
  lines.push(`  return v;`);
  lines.push(`}`);
  lines.push(`function __m_div_i64(a, b) {`);
  lines.push(`  if (b === 0n) throw new Error("DivisionByZero: integer division by zero");`);
  lines.push(`  return __m_i64(a / b, 'div');`);
  lines.push(`}`);
  lines.push(`function __m_mod_i64(a, b) {`);
  lines.push(`  if (b === 0n) throw new Error("DivisionByZero: integer remainder by zero");`);
  lines.push(`  return __m_i64(a % b, 'rem');`);
  lines.push(`}`);
  lines.push(`function __m_div_f64(a, b) {`);
  lines.push(`  if (b === 0) throw new Error("DivisionByZero: float division by zero");`);
  lines.push(`  return a / b;`);
  lines.push(`}`);
  lines.push(`function __m_fmt(v) {`);
  lines.push(`  if (v === undefined || v === null) return 'void';`);
  lines.push(`  if (typeof v === 'bigint') return v.toString();`);
  lines.push(`  if (typeof v === 'number') return Number.isInteger(v) ? v + '.0' : String(v);`);
  lines.push(`  if (typeof v === 'boolean') return v ? 'true' : 'false';`);
  lines.push(`  if (typeof v === 'string') return v;`);
  lines.push(`  if (Array.isArray(v)) return '[' + v.map(__m_fmt).join(', ') + ']';`);
  lines.push(`  if (v instanceof Map) {`);
  lines.push(`    const entries = Array.from(v.entries()).sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0));`);
  lines.push(`    return '{' + entries.map(([k, val]) => k + ': ' + __m_fmt(val)).join(', ') + '}';`);
  lines.push(`  }`);
  lines.push(`  if (v && v.__enum) {`);
  lines.push(`    return v.payload.length === 0 ? v.__enum + '::' + v.variant : v.__enum + '::' + v.variant + '(' + v.payload.map(__m_fmt).join(', ') + ')';`);
  lines.push(`  }`);
  lines.push(`  if (v && v.__struct) {`);
  lines.push(`    return v.__struct + ' { ' + v.fields.map(__m_fmt).join(', ') + ' }';`);
  lines.push(`  }`);
  lines.push(`  return String(v);`);
  lines.push(`}`);
  lines.push(`function __m_intrinsic(sym, cap, args) {`);
  lines.push(`  __m_require_cap(cap, sym);`);
  lines.push(`  switch (sym) {`);
  lines.push(`    case 'console.print': {`);
  lines.push(`      const line = args.map(__m_fmt).join(' ');`);
  lines.push(`      __m_stdout.push(line);`);
  lines.push(`      console.log(line);`);
  lines.push(`      return undefined;`);
  lines.push(`    }`);
  lines.push(`    case 'std::math::abs': return __m_i64(args[0] < 0n ? -args[0] : args[0], 'abs');`);
  lines.push(`    case 'std::math::abs_f64': return Math.abs(args[0]);`);
  lines.push(`    case 'std::math::min': return args[0] < args[1] ? args[0] : args[1];`);
  lines.push(`    case 'std::math::max': return args[0] > args[1] ? args[0] : args[1];`);
  lines.push(`    case 'std::math::sqrt': return Math.sqrt(args[0]);`);
  lines.push(`    case 'std::str::upper': return String(args[0]).toUpperCase();`);
  lines.push(`    case 'std::str::lower': return String(args[0]).toLowerCase();`);
  lines.push(`    case 'std::str::trim': return String(args[0]).trim();`);
  lines.push(`    case 'std::str::contains': return String(args[0]).includes(String(args[1]));`);
  lines.push(`    case 'time.now': return BigInt(Date.now());`);
  lines.push(`    case 'fs.read_text': {`);
  lines.push(`      if (!__m_vfs.has(args[0])) throw new Error("File not found in virtual workspace: " + args[0]);`);
  lines.push(`      return __m_vfs.get(args[0]);`);
  lines.push(`    }`);
  lines.push(`    case 'fs.write_text': { __m_vfs.set(args[0], __m_fmt(args[1])); return true; }`);
  lines.push(`    default: return '';`);
  lines.push(`  }`);
  lines.push(`}`);
  lines.push(``);

  for (const g of mir.globals) {
    lines.push(`let __g_${g.slot} = undefined; // ${g.name}`);
  }

  for (const fn of mir.functions) {
    lines.push(emitJsFunction(fn));
  }

  const entryCall = mir.entryFunction ? `__fn_${sanitizeIdent(mir.entryFunction)}()` : 'undefined';
  const initCall = mir.functions.some((f) => f.name === '__init__') && mir.entryFunction !== '__init__'
    ? `__fn___init__();\n  `
    : '';

  lines.push(`export function __runManifestModule() {`);
  lines.push(`  __m_stdout.length = 0;`);
  lines.push(`  ${initCall}const result = ${entryCall};`);
  lines.push(`  return { returnValue: __m_fmt(result), stdout: [...__m_stdout] };`);
  lines.push(`}`);

  const jsCode = lines.join('\n');
  const escapedCode = jsCode.replace(/^export function __runManifestModule/m, 'function __runManifestModule').replace(/<\/script>/gi, '<\\/script>');

  const htmlPreview = `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="utf-8" />
  <title>${escapeHtml(mir.moduleName)} — Manifest Web Target</title>
  <style>
    * { box-sizing: border-box; }
    body { margin: 0; padding: 24px; background: #181818; color: #e4e4e7; font-family: ui-sans-serif, system-ui, -apple-system, sans-serif; }
    .header { display: flex; align-items: baseline; justify-content: space-between; border-bottom: 1px solid #2d2d2d; padding-bottom: 12px; margin-bottom: 16px; }
    .title { font-size: 15px; font-weight: 600; color: #f4f4f5; }
    .meta { font-size: 12px; color: #a1a1aa; font-family: ui-monospace, monospace; }
    .section-label { font-size: 12px; color: #a1a1aa; margin-bottom: 8px; }
    pre { margin: 0 0 16px 0; padding: 14px; background: #1f1f1f; border: 1px solid #2d2d2d; border-radius: 6px; font-family: ui-monospace, SFMono-Regular, Menlo, monospace; font-size: 13px; line-height: 1.55; white-space: pre-wrap; word-break: break-word; }
    .ret { color: #38bdf8; }
    .err { color: #f87171; border-color: #7f1d1d; background: #261717; }
  </style>
</head>
<body>
  <div class="header">
    <div class="title">${escapeHtml(mir.moduleName)}</div>
    <div class="meta">Target: JavaScript / Web · Capabilities: ${escapeHtml(mir.requires.join(', ') || 'pure')}${!networkAllowed ? ' · Network Sandboxed' : ''}</div>
  </div>
  <div class="section-label">Standard Output</div>
  <pre id="stdout">(no console output)</pre>
  <div class="section-label">Return Value</div>
  <pre id="retval" class="ret">void</pre>
  <script>
    window.addEventListener('error', (e) => {
      window.parent.postMessage({ type: 'CONSOLE_ERROR', args: [e.message] }, '*');
    });
    try {
      ${escapedCode}
      const res = __runManifestModule();
      document.getElementById('stdout').textContent = res.stdout.length ? res.stdout.join('\\n') : '(no console output)';
      document.getElementById('retval').textContent = res.returnValue;
      window.parent.postMessage({ type: 'STATE_UPDATE', state: { returnValue: res.returnValue, stdoutLines: res.stdout.length, target: 'web-js' } }, '*');
    } catch (err) {
      const outEl = document.getElementById('retval');
      outEl.className = 'err';
      outEl.textContent = err && err.message ? err.message : String(err);
      console.error(err && err.message ? err.message : String(err));
    }
  </script>
</body>
</html>`;

  return {
    jsCode,
    htmlPreview,
    enforcedCapabilities: {
      allowed: mir.requires,
      denied: mir.denies,
      networkBlocked: !networkAllowed,
    },
  };
}

function sanitizeIdent(s: string): string {
  return s.replace(/[^a-zA-Z0-9_]/g, '_');
}

function escapeHtml(s: string): string {
  return s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}

function emitJsFunction(fn: MIRFunction): string {
  const params = fn.params.map((p) => `__l_${p.slot}`).join(', ');
  const out: string[] = [];
  out.push(`function __fn_${sanitizeIdent(fn.name)}(${params}) {`);
  for (let i = fn.params.length; i < fn.locals.length; i++) {
    out.push(`  let __l_${i} = undefined;`);
  }
  for (const s of fn.body) {
    emitJsStmt(s, '  ', out);
  }
  out.push(`}`);
  return out.join('\n');
}

function emitJsStmt(stmt: MIRStmt, indent: string, out: string[]): void {
  switch (stmt.kind) {
    case 'StoreLocal':
      out.push(`${indent}__l_${stmt.slot} = ${emitJsExpr(stmt.value)};`);
      break;
    case 'StoreGlobal':
      out.push(`${indent}__g_${stmt.slot} = ${emitJsExpr(stmt.value)};`);
      break;
    case 'ArraySet':
      out.push(`${indent}${emitJsExpr(stmt.array)}[Number(${emitJsExpr(stmt.index)})] = ${emitJsExpr(stmt.value)};`);
      break;
    case 'MapSetStmt':
      out.push(`${indent}${emitJsExpr(stmt.map)}.set(__m_fmt(${emitJsExpr(stmt.key)}), ${emitJsExpr(stmt.value)});`);
      break;
    case 'FieldSet':
      out.push(`${indent}${emitJsExpr(stmt.object)}.fields[${stmt.fieldIndex}] = ${emitJsExpr(stmt.value)};`);
      break;
    case 'ExprStmt':
      out.push(`${indent}${emitJsExpr(stmt.expr)};`);
      break;
    case 'If':
      out.push(`${indent}if (${emitJsExpr(stmt.condition)}) {`);
      for (const s of stmt.thenBranch) emitJsStmt(s, indent + '  ', out);
      if (stmt.elseBranch.length > 0) {
        out.push(`${indent}} else {`);
        for (const s of stmt.elseBranch) emitJsStmt(s, indent + '  ', out);
      }
      out.push(`${indent}}`);
      break;
    case 'While':
      out.push(`${indent}while (${emitJsExpr(stmt.condition)}) {`);
      for (const s of stmt.body) emitJsStmt(s, indent + '  ', out);
      out.push(`${indent}}`);
      break;
    case 'Break':
      out.push(`${indent}break;`);
      break;
    case 'Continue':
      out.push(`${indent}continue;`);
      break;
    case 'Return':
      out.push(`${indent}return ${stmt.value ? emitJsExpr(stmt.value) : 'undefined'};`);
      break;
    case 'Match': {
      out.push(`${indent}__l_${stmt.tempSlot} = ${emitJsExpr(stmt.subject)};`);
      stmt.arms.forEach((arm, idx) => {
        const prefix = idx === 0 ? 'if' : 'else if';
        if (arm.pattern.kind === 'Wildcard') {
          out.push(`${indent}${idx === 0 ? '{' : 'else {'}`);
        } else if (arm.pattern.kind === 'Literal') {
          const lit =
            arm.pattern.litKind === 'i64'
              ? `${arm.pattern.value}n`
              : JSON.stringify(arm.pattern.value);
          out.push(`${indent}${prefix} (__l_${stmt.tempSlot} === ${lit}) {`);
        } else {
          out.push(`${indent}${prefix} (__l_${stmt.tempSlot} && __l_${stmt.tempSlot}.tag === ${arm.pattern.variantTag}) {`);
          arm.pattern.bindingSlots.forEach((b, bIdx) => {
            out.push(`${indent}  __l_${b.slot} = __l_${stmt.tempSlot}.payload[${bIdx}];`);
          });
        }
        for (const s of arm.body) emitJsStmt(s, indent + '  ', out);
        out.push(`${indent}}`);
      });
      break;
    }
  }
}

function emitJsExpr(expr: MIRExpr): string {
  switch (expr.kind) {
    case 'ConstInt':
      return `${expr.value}n`;
    case 'ConstFloat':
      return Number.isInteger(expr.value) ? `${expr.value}.0` : String(expr.value);
    case 'ConstBool':
      return expr.value ? 'true' : 'false';
    case 'ConstStr':
      return JSON.stringify(expr.value);
    case 'ConstVoid':
      return 'undefined';
    case 'LoadLocal':
      return `__l_${expr.slot}`;
    case 'LoadGlobal':
      return `__g_${expr.slot}`;
    case 'Unary':
      if (expr.op === '-' && expr.operand.type.kind === 'i64') {
        return `__m_i64(-(${emitJsExpr(expr.operand)}), 'neg')`;
      }
      return `(${expr.op}(${emitJsExpr(expr.operand)}))`;
    case 'Cast':
      if (expr.castKind === 'i64_to_f64') return `Number(${emitJsExpr(expr.operand)})`;
      if (expr.castKind === 'f64_to_i64') return `BigInt(Math.trunc(${emitJsExpr(expr.operand)}))`;
      return `__m_fmt(${emitJsExpr(expr.operand)})`;
    case 'Binary': {
      const l = emitJsExpr(expr.left);
      const r = emitJsExpr(expr.right);
      const isStr =
        expr.op === '+' &&
        (expr.type.kind === 'str' || expr.left.type.kind === 'str' || expr.right.type.kind === 'str');
      if (isStr) return `(__m_fmt(${l}) + __m_fmt(${r}))`;
      if (expr.left.type.kind === 'i64' && expr.right.type.kind === 'i64') {
        if (expr.op === '+') return `__m_i64((${l}) + (${r}), 'add')`;
        if (expr.op === '-') return `__m_i64((${l}) - (${r}), 'sub')`;
        if (expr.op === '*') return `__m_i64((${l}) * (${r}), 'mul')`;
        if (expr.op === '/') return `__m_div_i64(${l}, ${r})`;
        if (expr.op === '%') return `__m_mod_i64(${l}, ${r})`;
      }
      if (expr.left.type.kind === 'f64' && expr.op === '/') {
        return `__m_div_f64(${l}, ${r})`;
      }
      if (expr.op === '==') return `(${l} === ${r})`;
      if (expr.op === '!=') return `(${l} !== ${r})`;
      return `(${l} ${expr.op} ${r})`;
    }
    case 'CallFunction':
      return `__fn_${sanitizeIdent(expr.callee)}(${expr.args.map(emitJsExpr).join(', ')})`;
    case 'CallIntrinsic':
      return `__m_intrinsic(${JSON.stringify(expr.symbol)}, ${JSON.stringify(expr.capability)}, [${expr.args.map(emitJsExpr).join(', ')}])`;
    case 'ArrayNew':
      return `[${expr.elements.map(emitJsExpr).join(', ')}]`;
    case 'ArrayGet':
      return `${emitJsExpr(expr.array)}[Number(${emitJsExpr(expr.index)})]`;
    case 'ArrayLen':
      return `BigInt(Array.isArray(${emitJsExpr(expr.target)}) ? ${emitJsExpr(expr.target)}.length : Array.from(String(${emitJsExpr(expr.target)})).length)`;
    case 'ArrayPush':
      return ` void (${emitJsExpr(expr.array)}.push(${emitJsExpr(expr.value)}))`;
    case 'MapNew':
      return `new Map([${expr.entries.map((e) => `[__m_fmt(${emitJsExpr(e.key)}), ${emitJsExpr(e.value)}]`).join(', ')}])`;
    case 'MapGet':
      return `${emitJsExpr(expr.map)}.get(__m_fmt(${emitJsExpr(expr.key)}))`;
    case 'MapSet':
      return ` void (${emitJsExpr(expr.map)}.set(__m_fmt(${emitJsExpr(expr.key)}), ${emitJsExpr(expr.value)}))`;
    case 'MapHas':
      return `${emitJsExpr(expr.map)}.has(__m_fmt(${emitJsExpr(expr.key)}))`;
    case 'StructNew':
      return `({ __struct: ${JSON.stringify(expr.structName)}, fields: [${expr.fields.map(emitJsExpr).join(', ')}] })`;
    case 'FieldGet':
      return `${emitJsExpr(expr.object)}.fields[${expr.fieldIndex}]`;
    case 'EnumNew':
      return `({ __enum: ${JSON.stringify(expr.enumName)}, variant: ${JSON.stringify(expr.variantName)}, tag: ${expr.variantTag}, payload: [${expr.args.map(emitJsExpr).join(', ')}] })`;
    case 'TryPropagate':
      return `((__r) => { if (__r && __r.tag === 1) throw new Error(__m_fmt(__r)); return __r ? __r.payload[0] : __r; })(${emitJsExpr(expr.operand)})`;
  }
}
